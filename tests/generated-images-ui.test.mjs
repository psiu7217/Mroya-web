import test, {after} from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {createServer} from 'vite';

const vite=await createServer({mode:'design',server:{middlewareMode:true},appType:'custom'});
after(()=>vite.close());
const {FilesView}=await vite.ssrLoadModule('/src/components/FilesView.tsx');
const noop=()=>{};
const id='10000000-0000-4000-8000-000000000001';
const file={id,filename:'mroya-cat.png',title:'Generated cat',mime_type:'image/png',size_bytes:70,source:'generated',
 status:'ready',error_code:null,category:null,searchable:false,document_date:null,document_type:'generated_image',
 coverage:'complete',created_at:'2026-11-17T10:00:00Z',original_url:`/api/v1/documents/${id}/original/`,
 summary:'A cat',analysis_version:1,page_count:0,pages:[],facts:[],values:[],analysis_author:'model',analysis_model:'synthetic/image',processed_at:'2026-11-17T10:00:00Z'};
const runtime={rows:[file],categories:[],category:'generated',query:'',order:'newest',total:1,loading:false,loadingMore:false,error:null,
 hasMore:false,uploading:false,mutating:false,selectedId:id,detail:file,detailLoading:false,detailError:null,canDelete:true,
 onRefresh:noop,onMore:noop,onCategory:noop,onSearch:noop,onOrder:noop,onSelect:noop,onRetryDetail:noop,
 onUpload:async()=>true,onSave:async()=>true,onReprocess:noop,onCategorySearch:noop,onCreateCategory:async()=>true,onDelete:async()=>true};

test('generated collection displays its image, download, prompt and collection name',()=>{
 const html=renderToStaticMarkup(React.createElement(FilesView,{runtime}));
 assert.match(html,/Generated by Mroya/);
 assert.match(html,/Image prompt/);
 assert.match(html,/<img[^>]*src="\/api\/v1\/documents\//);
 assert.ok(html.includes(`href="${file.original_url}"`));
 assert.doesNotMatch(html,/>Reprocess</);
});

test('generated empty collection explains automatic saving from Chat',()=>{
 const html=renderToStaticMarkup(React.createElement(FilesView,{runtime:{...runtime,rows:[],total:0,selectedId:null,detail:null}}));
 assert.match(html,/Ask Mroya to create an image in Chat/);
});
